"""Vendored kexts and their upstream provenance.

The kexts in EFI/OC/Kexts are the source of truth. A build never reaches the
network: a clone already contains everything needed, which matters because the
EFI is usually prepared on a machine that is not the one being installed, and
often is not online. `--update` is the only thing that talks to GitHub, and it
only refreshes what is actually older than upstream.

    python3 tools/kexts.py check      # verify the tree against vendor/kexts.lock
    python3 tools/kexts.py relock     # rewrite the lock from the current tree
    python3 tools/kexts.py outdated   # ask GitHub what is newer (network)
"""
