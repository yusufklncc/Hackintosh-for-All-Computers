def digest(bundle):
    """Hash of a kext bundle: every file, path included, order fixed."""
    h = hashlib.sha256()
    for p in sorted(bundle.rglob('*')):
        if p.is_file():
            h.update(str(p.relative_to(bundle)).encode())
            h.update(p.read_bytes())
    return h.hexdigest()


def version(bundle):
    """Some kexts set only CFBundleVersion, so fall back rather than report blank."""
    info = bundle / 'Contents' / 'Info.plist'
    if not info.exists():
        return ''
    with open(info, 'rb') as fh:
        d = plistlib.load(fh)
    return d.get('CFBundleShortVersionString') or d.get('CFBundleVersion') or ''


def scan():
    out = {}
    for b in sorted(KEXTS.glob('*.kext')):
        out[b.name] = {'version': version(b), 'sha256': digest(b),
                       'upstream': UPSTREAM.get(b.name) or ''}
    return out


def latest(repo):
    try:
        with urllib.request.urlopen(f'https://api.github.com/repos/{repo}/releases/latest') as r:
            return json.load(r).get('tag_name', '')
    except urllib.error.URLError:
        return ''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('action', choices=('check', 'relock', 'outdated'))
    a = ap.parse_args()
    have = scan()

    if a.action == 'relock':
        ocgen.write_toml(LOCK, {'kext': have},
                         '# Vendored kexts. Generated by tools/kexts.py relock.\n'
                         '# sha256 covers every file in the bundle, so a partial\n'
                         '# or truncated checkout is caught before it is copied.\n')
        print(f'  locked {len(have)} kexts -> {LOCK}')
        return 0

    if a.action == 'check':
        if not LOCK.exists():
            sys.exit(f'{LOCK} missing; run: python3 tools/kexts.py relock')
        want = ocgen.read_toml(LOCK)['kext']
        bad = 0
        for name in sorted(set(want) | set(have)):
            if name not in have:
                print(f'  MISSING  {name}'); bad += 1
            elif name not in want:
                print(f'  UNLOCKED {name}'); bad += 1
            elif have[name]['sha256'] != want[name]['sha256']:
                print(f'  CHANGED  {name}  {want[name]["sha256"][:12]} -> '
                      f'{have[name]["sha256"][:12]}'); bad += 1
        print(f'  {len(have) - bad}/{len(have)} kexts match the lock')
        return 1 if bad else 0

    width = max(len(k) for k in have)
    stale = 0
    for name, info in have.items():
        repo = info['upstream']
        if not repo:
            print(f'  {name:{width}s} {info["version"]:10s} vendored only')
            continue
        up = latest(repo) or '?'
        # tags and bundle versions are numbered differently by some projects, so
        # this is a prompt to look rather than a verdict
        same = up in ('?', info['version']) or up.lstrip('v') == info['version']
        mark = '' if same else '  <- differs from upstream tag'
        stale += bool(mark)
        print(f'  {name:{width}s} {info["version"]:10s} {repo} {up}{mark}')
    print(f'\n  {stale} kext(s) differ from their upstream tag; check each before updating')
    return 0


if __name__ == '__main__':
    sys.exit(main())
